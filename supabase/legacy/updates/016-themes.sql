-- Update 016: team page themes, start dates, and employee numbers.
--
-- Run once in Supabase → SQL Editor, after 015. Safe to re-run.
-- Run it BEFORE pushing the site version with themes.
--
-- After this update:
--   * Each person picks their own theme (Classic, Pixel, Pocket Trainer, Cat Café,
--     Catnip, Chill Leaf) and turns sound effects on or off. Saved to their own
--     account, so it follows them to any phone. Only they can change it: not even
--     a manager can read or set someone else's.
--   * Managers can set each person's start date (Team tab), used for the Pocket
--     Trainer card and badges.
--   * Everyone gets an employee number, in the order they were added.
--   * my_total_minutes(): all the time the signed-in person has ever clocked,
--     for the Pocket Trainer card.

-- ---------- 1. Start date and employee number ----------

alter table public.employees add column if not exists started_on date;
alter table public.employees add column if not exists staff_no integer generated by default as identity;

-- ---------- 2. Each person's own theme ----------

create table if not exists public.employee_prefs (
  employee_id  uuid primary key references public.employees (id) on delete cascade,
  theme        text not null default 'classic' check (theme in ('classic', 'pixel', 'trainer', 'cats', 'catnip', 'leaf')),
  sounds       boolean not null default false,
  updated_at   timestamptz not null default now()
);
alter table public.employee_prefs enable row level security;

-- Only your own. (No manager rule on purpose.)
drop policy if exists "Own theme only" on public.employee_prefs;
create policy "Own theme only" on public.employee_prefs
  for select to authenticated using (employee_id = (select public.my_employee_id()));

-- Saving goes through this function, which only ever touches your own row.
create or replace function public.set_my_theme(new_theme text, new_sounds boolean default false)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := public.my_employee_id();
begin
  if me is null then
    raise exception 'Not on the team list';
  end if;
  insert into employee_prefs (employee_id, theme, sounds, updated_at)
  values (me, new_theme, coalesce(new_sounds, false), now())
  on conflict (employee_id) do update set theme = excluded.theme, sounds = excluded.sounds, updated_at = now();
end;
$$;

-- ---------- 3. All my clocked time ----------

create or replace function public.my_total_minutes()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(extract(epoch from (coalesce(p.clock_out, now()) - p.clock_in)) / 60), 0)::bigint
    from punches p
   where p.employee_id = public.my_employee_id();
$$;

revoke all on function public.set_my_theme(text, boolean) from public, anon;
revoke all on function public.my_total_minutes() from public, anon;
grant execute on function public.set_my_theme(text, boolean) to authenticated;
grant execute on function public.my_total_minutes() to authenticated;

